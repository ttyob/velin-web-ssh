import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../terminal/package.json', import.meta.url));
const { chromium } = require('playwright-core');
const base = process.env.VELIN_MOBILE_PREVIEW_URL || 'http://127.0.0.1:8388/';
const output = new URL('../../artifacts/mobile-context-menu-015/screenshots/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (/overflowed|RenderFlex|EXCEPTION CAUGHT/.test(m.text())) errors.push(m.text()); });
  const button = name => page.getByRole('button', { name, exact: true });
  const settle = () => page.waitForTimeout(500);
  async function action(name, pane = 0) {
    await button('终端操作').nth(pane).tap();
    await settle();
    const item = page.getByText(name, { exact: false }).last();
    for (let i = 0; i < 7; i++) {
      const box = await item.boundingBox();
      if (box && box.y >= 190 && box.y + box.height < 810) break;
      await page.mouse.move(200, 600);
      await page.mouse.wheel(0, 350);
      await settle();
    }
    await item.tap();
    await settle();
  }
  await page.goto(base);
  await page.locator('flt-semantics-placeholder').waitFor({ state: 'attached' });
  await page.evaluate(() => document.querySelector('flt-semantics-placeholder').click());
  await page.getByRole('button', { name: /^Velin · 移动端开发 / }).tap();
  await button('展开输入').waitFor();
  const root = page.frames().find(f => f.url().endsWith('/terminal/index.html'));
  await root.waitForFunction(() => document.querySelector('.xterm-rows')?.textContent.includes('/workspace/velin'));
  await action('重命名会话');
  await page.getByRole('textbox').fill('手机测试 · 中文会话');
  await button('保存').tap();
  await settle();
  assert((await page.locator('flt-semantics').allTextContents()).some(text => text.includes('手机测试 · 中文会话')));
  assert.equal(root.isDetached(), false);
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.evaluate(() => navigator.clipboard.writeText('hello\n中文粘贴'));
  await action('粘贴');
  await page.getByRole('textbox').tap();
  await settle();
  assert.equal(await page.getByRole('textbox').inputValue(), 'hello\n中文粘贴');
  await button('收起输入').tap();
  await action('全选终端内容');
  await button('复制').waitFor();
  assert(await button('复制').isEnabled());
  await button('复制').tap();
  assert((await page.evaluate(() => navigator.clipboard.readText())).includes('/workspace/velin'));
  await button('退出选择').tap();
  await action('终端工具');
  for (const name of ['打开当前目录', '打开 Agent', '分享会话', '主机监控', 'Git 管理', 'Docker 管理']) assert(await page.getByText(name, { exact: true }).count());
  await page.screenshot({ path: new URL('tools-menu.png', output).pathname });
  await page.getByText('打开当前目录', { exact: true }).tap();
  await settle();
  await action('上下分屏');
  await page.getByText('控制台界面优化', { exact: false }).tap();
  await settle();
  assert.equal(await page.locator('iframe').count(), 2);
  assert.equal(root.isDetached(), false, 'Split recreated original terminal');
  await page.screenshot({ path: new URL('split-vertical.png', output).pathname });
  await action('关闭分屏', 1);
  assert.equal(await page.locator('iframe').count(), 1);
  assert.equal(root.isDetached(), false, 'Closing a pane disposed original terminal');
  await action('左右分屏');
  await page.getByText('控制台界面优化', { exact: false }).tap();
  await settle();
  await page.setViewportSize({ width: 360, height: 780 });
  await settle();
  await page.screenshot({ path: new URL('split-horizontal.png', output).pathname });
  assert.equal(await page.locator('iframe').count(), 2);
  assert.deepEqual(errors, []);
  console.log('Android menu preview passed: rename, clipboard paste, select/copy all, six tools, both split directions, pane close, retained terminal instance, narrow layout.');
} finally { await browser.close(); }
